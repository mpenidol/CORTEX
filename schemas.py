# --- 1.2 Structured Output From the Asset Agent --- 

class MappedAsset(BaseModel):
    instance_id: str = Field(description="The 'instance_id' generated by the Semantic Agent (e.g., 'monitor_1')")
    requested_asset: str = Field(description="The name of the asset requested by the Semantic Agent")
    matched_db_id: str | None = Field(description="The exact 'db_id' from the Database that best matches. Return null (None) if there is nothing remotely similar.")
    reason: str = Field(description="A very short explanation of why this item was chosen or why it returned null.")

class AssetMappingReport(BaseModel):
    mappings: list[MappedAsset]

